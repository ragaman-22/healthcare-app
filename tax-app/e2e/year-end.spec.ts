import { expect, test } from '@playwright/test'
import { formAlert } from './helpers'

test('2025年分: 帳簿 → 年次締め → 変更不可 → 申告書データ作成 → 締めの取り消し', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: '初期設定から試す' }).click()
  await page.waitForURL('**/onboarding')
  const next = () => page.getByRole('button', { name: '次へ' }).click()
  await page.locator('select').nth(0).selectOption('2025')
  await page.locator('select').nth(1).selectOption('design')
  await next()
  await page.check('input[value=blue]')
  await page.check('input[value=paper_55]')
  await next()
  await page.locator('select').first().selectOption('東京都')
  await page.locator('input').first().fill('サンプル区')
  await page.fill('input[type=date]', '1990-01-01')
  await next()
  await page.locator('input[inputmode=numeric]').last().fill('400000')
  for (let i = 0; i < 3; i++) await next()
  await page.check('input[value=exempt]')
  await page.locator('select').first().selectOption('0.05')
  for (let i = 0; i < 2; i++) await next()
  await page.getByRole('button', { name: '保存してホームへ' }).click()
  await page.waitForURL('**/home')

  await page.goto('/journal/new')
  await page.fill('input[name=date]', '2025-01-01')
  await page.fill('input[name=description]', '開業時の残高')
  const sel = page.locator('select[aria-label=勘定科目]')
  const amt = page.locator('input[aria-label=金額]')
  await sel.nth(0).selectOption('102')
  await amt.nth(0).fill('500000')
  await sel.nth(1).selectOption('300')
  await amt.nth(1).fill('500000')
  await page.locator('button[type=submit]').click()
  await page.waitForURL('**/journal?saved=1')

  await page.goto('/sales/new')
  await page.fill('input[name=occurredOn]', '2025-03-31')
  await page.fill('input[name=counterparty]', 'A社')
  await page.fill('input[name=amount]', '3000000')
  await page.getByText('入金済み', { exact: true }).click()
  await page.fill('input[name=settledOn]', '2025-03-31')
  await page.getByRole('button', { name: '保存する' }).click()
  await page.waitForURL('**/sales?saved=1')

  await page.goto('/return')
  await expect(page.getByText('年次締めが済んでいません')).toBeVisible()
  await page.check('input[name=confirm]')
  await page.getByRole('button', { name: '2025年を締める' }).click()
  await page.waitForURL('**/return?closed=1')
  await expect(page.locator('section:has-text("現在の状態")').getByText('確認済み')).toBeVisible()

  await page.goto('/sales')
  await page.getByText('A社').click()
  await page.waitForURL(/\/sales\/[0-9a-f-]{36}$/)
  await page.fill('input[name=amount]', '3100000')
  await page.getByRole('button', { name: '保存する' }).click()
  await expect(formAlert(page)).toContainText('締め済みの年')

  await page.goto('/return')
  await page.getByRole('button', { name: '申告書データを作成する' }).click()
  await page.waitForURL(/\/return\/history\/[0-9a-f-]{36}$/)
  await expect(page.getByText('確認済み（対応範囲内）')).toBeVisible()
  await expect(page.getByText('正式な様式ではありません')).toBeVisible()
  // 所得 300万 − 55万 = 245万、所得控除 40万＋88万 → 課税所得 117万
  await expect(page.locator('section:has-text("税金の計算") div:has-text("課税される所得金額")').first()).toContainText('1,170,000円')

  await page.goto('/return')
  await page.getByRole('button', { name: /締めを取り消す/ }).click()
  await page.waitForURL('**/return?reopened=1')
})
